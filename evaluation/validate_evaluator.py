"""
EXP-001: validate the SAFE-SOP automated evaluator against drafts with known, injected defects.

Run from the project root:
    .venv\\Scripts\\python evaluation\\validate_evaluator.py

Writes results/evaluator_validation_<evaluator version>[_<suffix>].json (every case) and .md
(summary), so results from different evaluator versions sit side by side. An optional suffix
(first argument) keeps a run on a newer test set from overwriting an earlier one, e.g.
    validate_evaluator.py testset-v2
No API key is needed: the drafts are built from the test set, not generated by Gemini.
"""
import json
import random
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.safety_evaluator import EVALUATOR_VERSION, evaluate_revision  # noqa: E402

TESTSET = ROOT / "evaluation" / "testset.json"
RESULTS = ROOT / "results"
BOOTSTRAP_SAMPLES = 2000
BOOTSTRAP_SEED = 1  # fixed, so the intervals are reproducible
COUNTED_SEVERITIES = {"critical", "high", "review"}  # "info" findings are not counted as detections

UNSUPPORTED_STEP = "Spray the surrounding floor with degreasing foam and wipe it dry."

# (case suffix, defect operations, expected finding types, expected status)
STANDARD_DEFECTS = [
    ("CLEAN", [], [], "pass_automated"),
    ("MISSING-WARNING", [{"op": "delete_warning", "index": 0}], ["missing_warning"], "fail"),
    ("ORDER-SWAP", [{"op": "swap_steps", "a": 3, "b": 4}], ["step_order_violation"], "fail"),
    ("UNSUPPORTED-STEP", [{"op": "insert_step", "after": 3, "text": UNSUPPORTED_STEP}],
     ["unsupported_instruction"], "fail"),
    ("UNSUPPORTED-VALUE", [{"op": "append_to_step", "index": 2, "text": " for 47 seconds"}],
     ["unsupported_value"], "fail"),
    ("OMITTED-STEP", [{"op": "delete_step", "index": 4}], ["omitted_step"], "fail"),
    ("DUPLICATED-STEP", [{"op": "duplicate_step", "index": 3}], ["duplicated_step"], "needs_review"),
    ("CONFLICT-NEGATION", [{"op": "negate_step", "index": 1}], ["conflicting_instruction"], "fail"),
]


def render_sop(title, purpose, warnings, steps):
    lines = [title, f"Purpose: {purpose}", "", "SAFETY WARNINGS", *warnings, "", "PROCEDURE"]
    lines += [f"{number}. {text}" for number, text in enumerate(steps, start=1)]
    return "\n".join(lines)


def apply_ops(warnings, steps, ops):
    warnings, steps = list(warnings), list(steps)
    for op in ops:
        kind = op["op"]
        if kind == "delete_warning":
            del warnings[op["index"]]
        elif kind == "replace_warning":
            warnings[op["index"]] = op["text"]
        elif kind == "replace_step":
            steps[op["index"]] = op["text"]
        elif kind == "delete_step":
            del steps[op["index"]]
        elif kind == "swap_steps":
            steps[op["a"]], steps[op["b"]] = steps[op["b"]], steps[op["a"]]
        elif kind == "insert_step":
            steps.insert(op["after"] + 1, op["text"])
        elif kind == "append_to_step":
            steps[op["index"]] = steps[op["index"]].rstrip(".") + op["text"] + "."
        elif kind == "duplicate_step":
            steps.insert(op["index"] + 1, steps[op["index"]])
        elif kind == "negate_step":
            text = steps[op["index"]]
            steps[op["index"]] = "Do not " + text[0].lower() + text[1:]
        else:
            raise ValueError(f"Unknown op: {kind}")
    return warnings, steps


def render_draft(sop, warnings, steps, request):
    # The fake model output claims every warning was kept, like a real LLM might.
    # The evaluator must ignore this claim and check the draft itself.
    return (
        "DRAFT:\n" + render_sop(sop["title"], sop["purpose"], warnings, steps)
        + f"\n\nCHANGE SUMMARY:\n- {request}\n\nPRESERVED SAFETY REQUIREMENTS:\n"
        "- All source warnings were retained.\n\nUNRESOLVED QUESTIONS:\n- None.\n"
    )


def build_cases(testset):
    cases = []
    for sop in testset["sops"]:
        original = render_sop(sop["title"], sop["purpose"], sop["warnings"], sop["steps"])
        changed_steps = list(sop["steps"])
        changed_steps[sop["change"]["step"]] = sop["change"]["new_text"]

        variants = [(suffix, ops, expected, status, "", "standard") for suffix, ops, expected, status in STANDARD_DEFECTS]
        variants += [
            (hard["id"], hard["ops"], hard["expected"], hard["expected_status"],
             hard.get("request_append", ""), hard["group"])
            for hard in sop["hard_cases"]
        ]
        for suffix, ops, expected, status, request_append, group in variants:
            request = sop["change"]["request"] + request_append
            warnings, steps = apply_ops(sop["warnings"], changed_steps, ops)
            cases.append({
                "case_id": f"{sop['id']}/{suffix}",
                "group": group,
                "hard": group != "standard",
                "change_request": request,
                "original": original,
                "draft": render_draft(sop, warnings, steps, request),
                "expected_types": sorted(expected),
                "expected_status": status,
            })
    return cases


def ratio(numerator, denominator):
    return round(numerator / denominator, 3) if denominator else None


def confusion(cases, kind):
    tp = sum(kind in c["expected_types"] and kind in c["detected_types"] for c in cases)
    fp = sum(kind not in c["expected_types"] and kind in c["detected_types"] for c in cases)
    fn = sum(kind in c["expected_types"] and kind not in c["detected_types"] for c in cases)
    return tp, fp, fn


def bootstrap_intervals(cases, types):
    """95% percentile-bootstrap intervals for per-type precision and recall, resampling cases.
    ponytail: cases from one SOP are not independent, so these intervals are too narrow;
    a cluster bootstrap over SOPs needs far more than 4 SOPs to mean anything (EXP-003)."""
    rng = random.Random(BOOTSTRAP_SEED)
    samples = {kind: {"precision": [], "recall": []} for kind in types}
    for _ in range(BOOTSTRAP_SAMPLES):
        resample = [rng.choice(cases) for _ in cases]
        for kind in types:
            tp, fp, fn = confusion(resample, kind)
            if tp + fp:
                samples[kind]["precision"].append(tp / (tp + fp))
            if tp + fn:
                samples[kind]["recall"].append(tp / (tp + fn))

    def interval(values):
        if not values:
            return None
        values = sorted(values)
        return [round(values[int(0.025 * (len(values) - 1))], 3), round(values[int(0.975 * (len(values) - 1))], 3)]

    return {kind: {name: interval(values) for name, values in metrics.items()} for kind, metrics in samples.items()}


def score(cases):
    types = sorted({t for c in cases for t in c["expected_types"] + c["detected_types"]})
    intervals = bootstrap_intervals(cases, types)
    per_type = {}
    for kind in types:
        tp, fp, fn = confusion(cases, kind)
        per_type[kind] = {"tp": tp, "fp": fp, "fn": fn,
                          "precision": ratio(tp, tp + fp), "recall": ratio(tp, tp + fn),
                          "precision_ci95": intervals[kind]["precision"], "recall_ci95": intervals[kind]["recall"]}

    defect_cases = [c for c in cases if c["expected_status"] != "pass_automated"]
    clean_cases = [c for c in cases if c["expected_status"] == "pass_automated"]
    per_group = {}
    for group in sorted({c["group"] for c in cases}):
        members = [c for c in cases if c["group"] == group]
        correct = sum(c["status"] == c["expected_status"] and c["expected_types"] == c["detected_types"] for c in members)
        per_group[group] = {"cases": len(members), "correct": correct, "accuracy": ratio(correct, len(members))}
    return {
        "per_group": per_group,
        "per_type": per_type,
        "cases": len(cases),
        "status_accuracy": ratio(sum(c["status"] == c["expected_status"] for c in cases), len(cases)),
        "exact_type_match_rate": ratio(sum(c["expected_types"] == c["detected_types"] for c in cases), len(cases)),
        "defect_cases": len(defect_cases),
        "defect_cases_flagged": ratio(sum(c["status"] != "pass_automated" for c in defect_cases), len(defect_cases)),
        "defect_cases_missed": [c["case_id"] for c in defect_cases if c["status"] == "pass_automated"],
        "clean_cases": len(clean_cases),
        "clean_false_alarm_rate": ratio(sum(c["status"] != "pass_automated" for c in clean_cases), len(clean_cases)),
    }


def type_table(per_type):
    def show(value, interval):
        if value is None:
            return "n/a"
        return f"{value} [{interval[0]}, {interval[1]}]" if interval else str(value)

    lines = ["| Finding type | TP | FP | FN | Precision [95% CI] | Recall [95% CI] |", "|---|---|---|---|---|---|"]
    for kind, m in per_type.items():
        lines.append(f"| {kind} | {m['tp']} | {m['fp']} | {m['fn']} | "
                     f"{show(m['precision'], m['precision_ci95'])} | {show(m['recall'], m['recall_ci95'])} |")
    return lines


def git_commit():
    try:
        commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True,
                                text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "status", "--porcelain", "src"], cwd=ROOT, capture_output=True,
                               text=True, check=True).stdout.strip()
        return commit + ("+uncommitted-src-changes" if dirty else "")
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def write_report(summary, cases, path):
    lines = [
        "# EXP-001 — Evaluator validation on injected defects",
        "",
        f"- Date (UTC): {summary['run_at']}",
        f"- Evaluator: `{summary['evaluator_version']}` (git `{summary['git_commit']}`)",
        f"- Test set: `evaluation/testset.json` — {summary['cases']} cases "
        f"({summary['defect_cases']} with a defect, {summary['clean_cases']} without)",
        "- Generator: none. Drafts are built from the test set, so ground truth is exact.",
        "",
        "## Case-level results",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Status accuracy (fail / needs_review / pass_automated) | {summary['status_accuracy']} |",
        f"| Exact finding-type match | {summary['exact_type_match_rate']} |",
        f"| Defect cases flagged (status is not pass_automated) | {summary['defect_cases_flagged']} |",
        f"| False alarms on defect-free cases | {summary['clean_false_alarm_rate']} |",
        f"| Defect cases missed entirely | {', '.join(summary['defect_cases_missed']) or 'none'} |",
        "",
        "## By case group",
        "",
        "`hard-dev` cases were known while designing the current rules; `hard-heldout` cases were written "
        "before the evaluator version that first targets them (v1.1 or v1.2) and were not used to tune it. "
        "They were written by the same author as the rules, so they are held out from tuning, not independent.",
        "",
        "| Group | Cases | Correct | Accuracy |",
        "|---|---|---|---|",
        *[f"| {g} | {m['cases']} | {m['correct']} | {m['accuracy']} |" for g, m in summary["per_group"].items()],
        "",
        "## Per finding type",
        "",
        "Counted per case (a type is detected or not in each case). 95% intervals: percentile bootstrap "
        f"over cases, {BOOTSTRAP_SAMPLES} resamples. Cases built from the same SOP are not independent, "
        "so the intervals are optimistic (too narrow). With only a few cases of a type, the interval collapses "
        "to a point when every case agrees (for example 2/2 gives [1.0, 1.0]); read that as 'too few cases "
        "to estimate', not as certainty.",
        "",
        *type_table(summary["per_type"]),
        "",
        "## Held-out cases only",
        "",
        "Cases in group `hard-heldout` (not used to design or tune the current rules). The 'should pass' "
        "held-out cases are included, so false alarms count here too.",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Cases | {summary['heldout']['cases']} |",
        f"| Status accuracy | {summary['heldout']['status_accuracy']} |",
        f"| Exact finding-type match | {summary['heldout']['exact_type_match_rate']} |",
        f"| Defect cases flagged | {summary['heldout']['defect_cases_flagged']} |",
        f"| False alarms on should-pass cases | {summary['heldout']['clean_false_alarm_rate']} |",
        f"| Defect cases missed entirely | {', '.join(summary['heldout']['defect_cases_missed']) or 'none'} |",
        "",
        *type_table(summary["heldout"]["per_type"]),
    ]
    lines += [
        "",
        "## All cases",
        "",
        "| Case | Expected | Detected | Expected status | Status | OK |",
        "|---|---|---|---|---|---|",
    ]
    for c in cases:
        ok = "yes" if c["status"] == c["expected_status"] and c["expected_types"] == c["detected_types"] else "**no**"
        lines.append(
            f"| {c['case_id']} | {', '.join(c['expected_types']) or '—'} | {', '.join(c['detected_types']) or '—'} "
            f"| {c['expected_status']} | {c['status']} | {ok} |"
        )
    lines += [
        "",
        "## Reading these results",
        "",
        "Standard cases test whether each rule fires on the defect it was designed for, so high scores there are "
        "expected and are not evidence of real-world accuracy. The `HARD-*` cases show known blind spots. Real "
        "Gemini drafts with human annotation (EXP-002) are needed before claiming real-world performance.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def main():
    testset = json.loads(TESTSET.read_text(encoding="utf-8"))
    cases = build_cases(testset)
    for case in cases:
        result = evaluate_revision(case["original"], case["draft"], case["change_request"])
        case["status"] = result["status"]
        case["metrics"] = result["metrics"]
        case["findings"] = result["findings"]
        case["detected_types"] = sorted({f["type"] for f in result["findings"] if f["severity"] in COUNTED_SEVERITIES})

    summary = {
        "experiment_id": "EXP-001",
        "run_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M"),
        "evaluator_version": EVALUATOR_VERSION,
        "git_commit": git_commit(),
        **score(cases),
        "heldout": score([c for c in cases if c["group"] == "hard-heldout"]),
    }
    RESULTS.mkdir(exist_ok=True)
    suffix = sys.argv[1] if len(sys.argv) > 1 else ""
    stem = f"evaluator_validation_{EVALUATOR_VERSION}" + (f"_{suffix}" if suffix else "")
    (RESULTS / f"{stem}.json").write_text(
        json.dumps({"summary": summary, "cases": cases}, indent=2), encoding="utf-8")
    write_report(summary, cases, RESULTS / f"{stem}.md")

    print(f"{summary['cases']} cases | status accuracy {summary['status_accuracy']} | "
          f"defects flagged {summary['defect_cases_flagged']} | clean false alarms {summary['clean_false_alarm_rate']}")
    print("  by group: " + ", ".join(f"{g} {m['correct']}/{m['cases']}" for g, m in summary["per_group"].items()))
    print(f"  written: results/{stem}.md")
    for c in cases:
        if c["status"] != c["expected_status"] or c["expected_types"] != c["detected_types"]:
            print(f"  MISMATCH {c['case_id']}: expected {c['expected_types']} / {c['expected_status']}, "
                  f"got {c['detected_types']} / {c['status']}")


if __name__ == "__main__":
    main()
