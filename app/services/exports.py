"""Exports: an approved version as DOCX or PDF with its approval record and change log, and the
automated evaluation report as PDF.

DOCX is written directly as WordprocessingML with the standard library (a .docx is a zip of a
few XML files), so no extra dependency is needed.
"""
import html
import io
import json
import zipfile
from xml.sax.saxutils import escape

import pymupdf
from fastapi import HTTPException

from app.db import connect_db
from src.safety_evaluator import extract_draft_section


def approved_record(version_id):
    """Everything an approved-version export shows. 409 unless the version is approved."""
    with connect_db() as connection:
        version = connection.execute(
            """SELECT v.*, d.filename, d.sha256 AS document_sha256, cr.description AS change_request
               FROM versions v JOIN documents d ON d.id = v.document_id
               LEFT JOIN change_requests cr ON cr.id = v.request_id WHERE v.id = ?""", (version_id,)).fetchone()
        if not version:
            raise HTTPException(status_code=404, detail="Version not found.")
        if version["status"] != "approved":
            raise HTTPException(status_code=409, detail="Only approved versions can be exported as controlled "
                                                        "documents. Download the draft instead.")
        approval = connection.execute(
            """SELECT * FROM review_history WHERE version_id = ? AND decision = 'approved'
               ORDER BY created_at DESC LIMIT 1""", (version_id,)).fetchone()
        reviews = connection.execute(
            "SELECT decision, reviewer, feedback, created_at FROM review_history WHERE version_id = ? ORDER BY created_at",
            (version_id,)).fetchall()
        lineage, parent_id = [], version["parent_version_id"]
        while parent_id and len(lineage) < 50:
            parent = connection.execute(
                """SELECT v.id, v.version_number, v.created_at, v.created_by, v.parent_version_id,
                          cr.description AS change_request
                   FROM versions v LEFT JOIN change_requests cr ON cr.id = v.request_id WHERE v.id = ?""",
                (parent_id,)).fetchone()
            if not parent:
                break
            lineage.append(parent)
            parent_id = parent["parent_version_id"]
    draft, _ = extract_draft_section(version["content"])
    summary = version["content"].split("CHANGE SUMMARY:", 1)[1].split("\n\n", 1)[0].strip() \
        if "CHANGE SUMMARY:" in version["content"] else ""
    return {"version": version, "approval": approval, "reviews": reviews, "lineage": lineage,
            "draft": draft, "summary": summary}


def approval_lines(record):
    version, approval = record["version"], record["approval"]
    return [
        ("Document", f"{version['filename']}, version {version['version_number']}"),
        ("Status", "APPROVED by a qualified reviewer"),
        ("Approved by", approval["reviewer"] if approval else "unknown"),
        ("Approved at (UTC)", approval["created_at"][:19].replace("T", " ") if approval else "unknown"),
        ("Approval justification", (approval["feedback"] if approval else "") or "None given"),
        ("Automated checks at approval",
         f"{approval['evaluation_status'] or 'not run'} ({approval['evaluator_version'] or 'no evaluation'})" if approval else "unknown"),
        ("Source PDF SHA-256", (approval["source_sha256"] if approval else None) or version["document_sha256"]),
        ("Approved text SHA-256", (approval["content_sha256"] if approval else None) or "not recorded"),
        ("Generated by", f"{version['created_by'] or 'unknown'} with {version['model'] or 'unknown model'}"),
    ]


def change_log(record):
    version = record["version"]
    rows = [(f"v{version['version_number']}", version["created_at"][:10], version["created_by"] or "",
             version["change_request"] or "")]
    rows += [(f"v{p['version_number']}", p["created_at"][:10], p["created_by"] or "", p["change_request"] or "")
             for p in record["lineage"]]
    return rows


# ---- DOCX (standard library) ----

def _run(text, bold=False, size=None):
    props = ("<w:b/>" if bold else "") + (f'<w:sz w:val="{size}"/>' if size else "")
    return f'<w:r>{f"<w:rPr>{props}</w:rPr>" if props else ""}<w:t xml:space="preserve">{escape(text)}</w:t></w:r>'


def _paragraph(*runs):
    return f"<w:p>{''.join(runs)}</w:p>"


def build_docx(record):
    body = [_paragraph(_run(f"{record['version']['filename']} - approved revision v{record['version']['version_number']}",
                            bold=True, size=32))]
    body += [_paragraph(_run(f"{label}: ", bold=True), _run(str(value))) for label, value in approval_lines(record)]
    body.append(_paragraph(_run("Change log", bold=True, size=26)))
    body += [_paragraph(_run(f"{number} ({date}, {author}): ", bold=True), _run(request))
             for number, date, author, request in change_log(record)]
    if record["summary"]:
        body.append(_paragraph(_run("Changes in this revision: ", bold=True), _run(record["summary"])))
    body.append(_paragraph(_run("Procedure", bold=True, size=26)))
    body += [_paragraph(_run(line)) for line in record["draft"].splitlines()]
    document = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
                '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
                f"<w:body>{''.join(body)}<w:sectPr/></w:body></w:document>")
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as docx:
        docx.writestr("[Content_Types].xml",
                      '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
                      '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
                      '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
                      '<Default Extension="xml" ContentType="application/xml"/>'
                      '<Override PartName="/word/document.xml" '
                      'ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
                      "</Types>")
        docx.writestr("_rels/.rels",
                      '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
                      '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                      '<Relationship Id="rId1" '
                      'Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" '
                      'Target="word/document.xml"/></Relationships>')
        docx.writestr("word/document.xml", document)
    return buffer.getvalue()


# ---- PDF (PyMuPDF Story, as for draft downloads) ----

def html_pdf(body_html):
    story = pymupdf.Story(html=body_html, user_css=(
        "body { font-family: sans-serif; font-size: 10pt; } h1 { font-size: 15pt; } h2 { font-size: 12pt; margin-top: 10pt; }"
        "p { margin: 0 0 3pt 0; } td, th { border: 1px solid #999; padding: 2pt 4pt; vertical-align: top; }"))
    buffer = io.BytesIO()
    writer = pymupdf.DocumentWriter(buffer)
    page, more = pymupdf.paper_rect("a4"), True
    while more:
        device = writer.begin_page(page)
        more, _ = story.place(page + (50, 50, -50, -50))
        story.draw(device)
        writer.end_page()
    writer.close()
    return buffer.getvalue()


def build_pdf(record):
    e = html.escape
    rows = "".join(f"<tr><th>{e(label)}</th><td>{e(str(value))}</td></tr>" for label, value in approval_lines(record))
    log = "".join(f"<tr><td>{e(n)}</td><td>{e(d)}</td><td>{e(a)}</td><td>{e(r)}</td></tr>" for n, d, a, r in change_log(record))
    lines = "".join(f"<p>{e(line) or '&nbsp;'}</p>" for line in record["draft"].splitlines())
    summary = f"<p><b>Changes in this revision:</b> {e(record['summary'])}</p>" if record["summary"] else ""
    return html_pdf(
        f"<h1>{e(record['version']['filename'])} - approved revision v{record['version']['version_number']}</h1>"
        f"<table>{rows}</table><h2>Change log</h2>"
        f"<table><tr><th>Version</th><th>Date</th><th>Author</th><th>Change request</th></tr>{log}</table>"
        f"{summary}<h2>Procedure</h2>{lines}")


def build_evaluation_report_pdf(version_id):
    """The latest automated evaluation of a version, any status. Not an approval document."""
    with connect_db() as connection:
        version = connection.execute(
            "SELECT v.version_number, v.status, d.filename FROM versions v JOIN documents d ON d.id = v.document_id "
            "WHERE v.id = ?", (version_id,)).fetchone()
        evaluation = connection.execute(
            "SELECT * FROM evaluations WHERE version_id = ? ORDER BY created_at DESC LIMIT 1", (version_id,)).fetchone()
    if not version:
        raise HTTPException(status_code=404, detail="Version not found.")
    if not evaluation:
        raise HTTPException(status_code=404, detail="This version has no automated evaluation yet.")
    e = html.escape
    metrics = json.loads(evaluation["metrics_json"])
    findings = json.loads(evaluation["findings_json"])
    status = {"pass_automated": "No rule fired (this is not a safety approval)", "needs_review": "Needs review",
              "fail": "Fail"}.get(evaluation["status"], evaluation["status"])
    metric_rows = "".join(f"<tr><th>{e(k)}</th><td>{e(json.dumps(v) if isinstance(v, (dict, list)) else str(v))}</td></tr>"
                          for k, v in metrics.items())
    finding_html = "".join(
        f"<h2>{e(f['severity'].upper())}: {e(f['type'].replace('_', ' '))}</h2><p>{e(f['detail'])}</p>"
        + (f"<p><b>Source{' (line ' + str(f['source_line']) + ')' if f.get('source_line') else ''}:</b> {e(f['source'])}</p>" if f.get("source") else "")
        + (f"<p><b>Draft{' (line ' + str(f['draft_line']) + ')' if f.get('draft_line') else ''}:</b> {e(f['draft'])}</p>" if f.get("draft") else "")
        + (f"<p><b>Evidence:</b> {e(str(f['evidence']))}</p>" if f.get("evidence") else "")
        for f in findings) or "<p>No automated rule fired. This is not a safety approval.</p>"
    return html_pdf(
        f"<h1>Automated evaluation report - {e(version['filename'])} v{version['version_number']}</h1>"
        f"<p><b>Result:</b> {e(status)}</p><p><b>Evaluator:</b> {e(evaluation['evaluator_version'])}, "
        f"run {e(evaluation['created_at'][:19].replace('T', ' '))} UTC</p>"
        f"<p><b>Review status of the version:</b> {e(version['status'])}</p>"
        "<p>Automated text checks flag problems for a qualified reviewer; they never approve a draft.</p>"
        f"<h2>Findings ({len(findings)})</h2>{finding_html}<h2>Metrics</h2><table>{metric_rows}</table>")
