import { Link, useNavigate, useParams } from "react-router";
import { ArrowDownToLine, ClipboardCheck, FileText, RefreshCw } from "lucide-react";
import { downloadApproved, downloadEvaluationReport, downloadTranslation, downloadVersion, getReviews, getVersion } from "../api.js";
import ReviewTimeline from "../components/ReviewTimeline.jsx";
import VersionEvidence from "../components/VersionEvidence.jsx";
import { Badge, EmptyState } from "../components/ui.jsx";
import { LANGUAGES, evaluationLabel, evaluationTone, statusLabel, statusTone } from "../components/labels.js";
import { useAuth, useNotice, useResource, useTitle } from "../state.jsx";

export default function VersionPage() {
  const { versionId } = useParams();
  const version = useResource(() => getVersion(versionId), [versionId]);
  const reviews = useResource(() => getReviews(versionId), [versionId]);
  const v = version.data;
  useTitle(v ? `Version ${v.version_number} · ${v.filename}` : "Version");
  const { can } = useAuth();
  const { show } = useNotice();
  const navigate = useNavigate();

  if (version.error) return <EmptyState icon={FileText} title="Version not available" text={version.error.message} action={<Link className="btn btn-primary" to="/documents">Back to documents</Link>} />;
  if (!v) return <p className="small-note">Loading version…</p>;

  const download = (format) => downloadVersion(v.id, v.version_number, format).catch((error) => show(`Download failed: ${error.message}`, "error"));

  return (
    <>
      <div className="page-intro">
        <div>
          <p className="title-block-kicker"><Link to={`/documents/${v.document_id}`}>{v.filename}</Link></p>
          <h1>Version {v.version_number}</h1>
          <p>{v.change_request || "No change request recorded."}</p>
          <p className="small-note">Generated from the original PDF{v.scope === "page" && v.target_page ? `, page ${v.target_page}` : ""} by {v.created_by || "unknown"} on {new Date(v.created_at).toLocaleString()} · {v.provider ? `${v.provider} / ` : ""}{v.model || "model not recorded"}{v.prompt_version ? ` · prompt ${v.prompt_version}` : ""}</p>
          {Boolean(v.fallback_used) && <p className="form-error">Generated by the fallback provider ({v.provider}) because the primary failed: {v.fallback_reason}</p>}
        </div>
        <div className="stack-badges">
          <Badge tone={evaluationTone[v.evaluation_status] || "gray"}>{evaluationLabel[v.evaluation_status] || "Not run"}</Badge>
          <Badge tone={statusTone(v.status)} dot>{statusLabel(v.status)}</Badge>
        </div>
      </div>

      <div className="action-row page-actions">
        {can("reviewer") && v.status !== "approved" && <Link className="btn btn-primary" to={`/versions/${v.id}/review`}><ClipboardCheck size={16} /> Review this version</Link>}
        {v.status === "approved" && <>
          <button className="btn btn-primary" onClick={() => downloadApproved(v.id, v.version_number, "docx").catch((error) => show(`Download failed: ${error.message}`, "error"))}><ArrowDownToLine size={16} /> Approved document (DOCX)</button>
          <button className="btn btn-secondary" onClick={() => downloadApproved(v.id, v.version_number, "pdf").catch((error) => show(`Download failed: ${error.message}`, "error"))}><ArrowDownToLine size={16} /> Approved document (PDF)</button>
        </>}
        <button className="btn btn-secondary" onClick={() => download("pdf")}><ArrowDownToLine size={16} /> Draft (PDF)</button>
        <button className="btn btn-secondary" onClick={() => downloadEvaluationReport(v.id, v.version_number).catch((error) => show(`Download failed: ${error.message}`, "error"))}><ArrowDownToLine size={16} /> Evaluation report (PDF)</button>
        <button className="btn btn-secondary" onClick={() => download("txt")}><ArrowDownToLine size={16} /> Text (.txt)</button>
        {can("author") && <button className="btn btn-secondary" onClick={() => navigate(`/documents/${v.document_id}`, { state: { parent: v } })}><RefreshCw size={16} /> Regenerate from original</button>}
      </div>

      <VersionEvidence versionId={v.id} documentId={v.document_id} onEvaluated={version.reload} />
      {v.translated_content && <section className="panel" aria-labelledby="translation-heading">
        <div className="panel-heading">
          <div><h2 id="translation-heading">{LANGUAGES[v.output_language]} translation</h2><p>Machine translation of this draft, checked by an independent back-translation (findings marked "translation" above). A native-speaker reviewer must read it; the English draft is the controlled text.</p></div>
          <button className="btn btn-secondary" onClick={() => downloadTranslation(v.id, v.version_number, v.output_language).catch((error) => show(`Download failed: ${error.message}`, "error"))}><ArrowDownToLine size={16} /> Translation (.txt)</button>
        </div>
        <pre className="draft-output" lang={v.output_language}>{v.translated_content}</pre>
      </section>}
      <ReviewTimeline reviews={reviews} status={v.status} />
    </>
  );
}
